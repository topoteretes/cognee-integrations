import { readFileSync } from "node:fs";
import { resolve } from "node:path";

import {
  capPassage,
  contextCharsLimit,
  minimizeContext,
  passageCharsLimit,
  passageSessionId,
  pruneEntities,
  pyLen,
  splitOnlyContext,
  splitPassages,
  trimRecallText,
} from "../../src/recall-text";

type Case = {
  kind: "trim" | "cap_passage" | "prune_entities" | "split_passages";
  name: string;
  note: string;
  input_text: string;
  session_id?: string;
  prompt?: string;
  passage_chars?: number | null;
  context_chars?: number | null;
  expected: Record<string, unknown>;
};

// The shared case table lives at integrations/conformance/recall_text_cases.json,
// generated by running the hook plugins' _recall_text.py. The Python suite
// (integrations/tests/tests/unit/test_recall_text_conformance.py) reads the same
// file, so the port and the original cannot drift apart unnoticed.
const casesPath = resolve(__dirname, "..", "..", "..", "conformance", "recall_text_cases.json");
const cases: Case[] = JSON.parse(readFileSync(casesPath, "utf-8"));
const ofKind = (kind: Case["kind"]) => cases.filter((c) => c.kind === kind);

const ENV_KEYS = ["COGNEE_RECALL_PASSAGE_CHARS", "COGNEE_RECALL_CONTEXT_CHARS"] as const;
const saved = Object.fromEntries(ENV_KEYS.map((k) => [k, process.env[k]]));
function restoreEnv(): void {
  for (const k of ENV_KEYS) {
    if (saved[k] === undefined) delete process.env[k];
    else process.env[k] = saved[k];
  }
}
// Cases with a null option rely on the defaults, so the knobs must be unset.
beforeEach(() => ENV_KEYS.forEach((k) => delete process.env[k]));
afterAll(restoreEnv);

describe("recall text trimming conformance", () => {
  it("covers every case kind", () => {
    expect(new Set(cases.map((c) => c.kind))).toEqual(
      new Set(["trim", "cap_passage", "prune_entities", "split_passages"]),
    );
  });

  it.each(ofKind("trim"))("trim: $name", (c) => {
    const result = trimRecallText(c.input_text, c.prompt ?? "", c.session_id ?? "", {
      passageChars: c.passage_chars,
      contextChars: c.context_chars,
    });
    expect(result).toEqual(c.expected);
  });

  it.each(ofKind("cap_passage"))("cap_passage: $name", (c) => {
    expect({ text: capPassage(c.input_text, c.passage_chars ?? 0) }).toEqual(c.expected);
  });

  it.each(ofKind("prune_entities"))("prune_entities: $name", (c) => {
    expect(pruneEntities(c.input_text)).toEqual(c.expected);
  });

  it.each(ofKind("split_passages"))("split_passages: $name", (c) => {
    const passages = splitPassages(c.input_text);
    expect({ passages, session_ids: passages.map(passageSessionId) }).toEqual(c.expected);
  });
});

describe("recall text trimming (TS-specific)", () => {
  afterEach(() => ENV_KEYS.forEach((k) => delete process.env[k]));

  it.each([
    ["", 2000],
    ["1500", 1500],
    [" 1500 ", 1500],
    ["1_500", 1500],
    ["+7", 7],
    ["0", 0],
    ["junk", 2000],
    ["1.5", 2000],
    ["-5", 2000],
  ])("reads the passage knob %j as %d", (raw, expected) => {
    process.env.COGNEE_RECALL_PASSAGE_CHARS = raw;
    expect(passageCharsLimit()).toBe(expected);
  });

  it("defaults the budget knob to 12000 and lets 0 disable it", () => {
    expect(contextCharsLimit()).toBe(12000);
    process.env.COGNEE_RECALL_CONTEXT_CHARS = "0";
    expect(contextCharsLimit()).toBe(0);
  });

  it("reads the knobs from the environment when no option is passed", () => {
    process.env.COGNEE_RECALL_PASSAGE_CHARS = "40";
    const body = "Session ID: s\n\n" + "a".repeat(30) + "\n\n" + "b".repeat(30);
    const { text, stats } = minimizeContext(`## Relevant passages\n${body}`);
    expect(stats.passages_capped).toBe(1);
    expect(text).toContain("…[+");
  });

  it("returns the same string when a passage needs no cap", () => {
    const passage = "short";
    expect(capPassage(passage, 1000)).toBe(passage);
  });

  it("treats null and undefined text as empty and unparsed", () => {
    for (const text of [null, undefined]) {
      const result = trimRecallText(text, "q", "s");
      expect(result).toEqual({
        context: "",
        guidance: "",
        stats: { parsed: false, chars_in: 0, history_chars: 0, chars_out: 0 },
      });
    }
  });

  it("matches an OpenClaw session id exactly, suffix included", () => {
    const own = "Session ID: open_claw_abc__2\n\nmine";
    const earlier = "Session ID: open_claw_abc\n\nbefore the dataset switch";
    const context = `## Relevant passages\n${own}\n---\n${earlier}`;
    const { text, stats } = minimizeContext(context, "open_claw_abc__2", { passageChars: 0 });
    expect(stats.passages_dropped).toBe(1);
    expect(text).toBe(`## Relevant passages\n${earlier}`);
  });

  it("splits layers and keeps an empty context slot parsed", () => {
    expect(splitOnlyContext("The question is: `q`\n`` ", "q").parsed).toBe(false);
    expect(splitOnlyContext("The question is: `q`\n``", "q")).toEqual({
      history: "",
      context: "",
      guidance: "",
      parsed: true,
    });
  });

  it("counts code points like Python len()", () => {
    expect(pyLen("😀a")).toBe(2);
    expect(pyLen("\ud83d")).toBe(1);
  });
});
